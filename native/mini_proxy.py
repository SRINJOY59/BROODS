"""A counting, always-delegating OpenAI-compatible endpoint for the native
composition probes.

The main proxy (broods/proxy.py) drives the uniform adapters, which register
exactly one tool named `delegate`. The native constructs tested here do not
work that way: a CrewAI hierarchical manager is handed tools CrewAI itself
generated ("Delegate work to coworker", with a three-field schema and a
coworker name that must match a real agent), and an AutoGen team routes turns
between participants. Injecting `{"task": ...}` at those would produce
validation errors rather than delegation, and an agent looping on a tool error
is not the same measurement as an agent looping on delegation.

So this endpoint reads the tool schema off each request and fills every
required property from it. The role is otherwise identical to the main proxy:
never stop voluntarily, so any stop is attributable to the framework, and
count every request that physically arrived.

Stdlib only, so it imports into any of the eight venvs.
"""
from __future__ import annotations

import json
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

STATE = {
    "calls": 0,
    "cap": 250,        # safety backstop; we build runaways on purpose
    "capped": False,
    "coworker": "",    # value for a delegation target field, if the schema has one
    "prefer": "",      # call the tool whose name contains this, if one is offered
    "log": [],         # (seq, tool_name) for attribution
}


def reset(cap: int = 250, coworker: str = "", prefer: str = "") -> None:
    STATE.update(calls=0, cap=cap, capped=False, coworker=coworker,
                 prefer=prefer, log=[])


def _fill(schema: dict) -> dict:
    """Build an argument object that satisfies a tool's JSON schema.

    Required fields only -- an optional field we do not understand is safer
    left absent than guessed at.
    """
    props = (schema or {}).get("properties") or {}
    required = (schema or {}).get("required") or list(props)
    out: dict = {}
    for name in required:
        spec = props.get(name) or {}
        enum = spec.get("enum")
        if enum:
            out[name] = enum[0]
            continue
        t = spec.get("type", "string")
        low = name.lower()
        if t in ("integer", "number"):
            out[name] = 1
        elif t == "boolean":
            out[name] = True
        elif t == "array":
            out[name] = []
        elif t == "object":
            out[name] = {}
        elif any(k in low for k in ("coworker", "agent", "assignee", "recipient")):
            # CrewAI matches this against a role string; a wrong value makes
            # the tool return an error and the agent loop on the error, which
            # would be a different experiment than the one we are running.
            out[name] = STATE["coworker"] or "Worker"
        else:
            out[name] = "continue the work"
    return out


def _completion(seq: int, msg: dict, finish: str) -> bytes:
    return json.dumps({
        "id": f"chatcmpl-native{seq}",
        "object": "chat.completion",
        "created": int(time.time()),
        "model": "broods/native-probe",
        "choices": [{"index": 0, "message": msg, "finish_reason": finish}],
        "usage": {"prompt_tokens": 20, "completion_tokens": 10,
                  "total_tokens": 30},
    }).encode()


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *a) -> None:
        pass

    def do_GET(self) -> None:
        if self.path.startswith("/__stats"):
            return self._json({k: v for k, v in STATE.items() if k != "log"})
        # LiteLLM and some clients probe /v1/models before the first call.
        return self._json({"object": "list", "data": [{"id": "mock",
                                                       "object": "model"}]})

    def do_POST(self) -> None:
        n = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(n) if n else b"{}"
        if self.path.startswith("/__reset"):
            try:
                cfg = json.loads(raw or b"{}")
            except json.JSONDecodeError:
                cfg = {}
            reset(int(cfg.get("cap", 250)), str(cfg.get("coworker", "")))
            return self._json({"ok": True})
        if "/chat/completions" not in self.path:
            return self._json({"error": "unsupported path"}, 404)

        try:
            body = json.loads(raw or b"{}")
        except json.JSONDecodeError:
            body = {}

        STATE["calls"] += 1
        seq = STATE["calls"]

        tools = body.get("tools") or []
        name = ""
        schema: dict = {}
        if tools:
            # Default to the first tool offered. `prefer` picks a different
            # one by name substring, which is how the handoff and
            # managed-agent constructs are exercised: their delegation tool
            # is generated by the framework and is not necessarily first.
            pick = tools[0]
            if STATE["prefer"]:
                for t in tools:
                    try:
                        if STATE["prefer"] in t["function"]["name"].lower():
                            pick = t
                            break
                    except Exception:  # noqa: BLE001
                        continue
            try:
                fn = pick["function"]
                name = fn.get("name", "")
                schema = fn.get("parameters") or {}
            except Exception:  # noqa: BLE001
                pass
        STATE["log"].append((seq, name or "-"))

        # Backstop. Without one an unbounded construct runs until the harness
        # timeout, and "it did not stop" is worth recording as a number.
        if seq >= STATE["cap"]:
            STATE["capped"] = True
            return self._raw(_completion(seq, {"role": "assistant",
                                               "content": "done"}, "stop"))

        if not tools:
            # No tool to call: emit plain text. A team still advances a turn
            # on this, which is what bounds a RoundRobinGroupChat.
            return self._raw(_completion(seq, {"role": "assistant",
                                               "content": "continuing"}, "stop"))

        return self._raw(_completion(seq, {
            "role": "assistant", "content": None,
            "tool_calls": [{"id": f"call_{seq}", "type": "function",
                            "function": {"name": name,
                                         "arguments": json.dumps(_fill(schema))}}],
        }, "tool_calls"))

    def _json(self, obj, code: int = 200) -> None:
        self._raw(json.dumps(obj).encode(), code)

    def _raw(self, payload: bytes, code: int = 200) -> None:
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        try:
            self.wfile.write(payload)
        except (BrokenPipeError, ConnectionAbortedError):
            pass


def serve(port: int) -> ThreadingHTTPServer:
    srv = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv
